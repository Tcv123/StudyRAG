/**
 * Splits dist/papers-config.js for Cloudflare Pages.
 *
 * The repo's papers-config.js is ~10 MB, nearly all of it each paper's
 * `questions` and `markSchemes`. Four pages load it, and three of them only
 * need the paper list. So the deployed copy keeps the list (~200 KB) and each
 * paper's questions + mark schemes move to dist/papers-data/<id>.json, which
 * window.loadPaperDetails fetches on demand. Each paper left behind gets
 * `details` (that file's path) and `partCount` (what paperParts would return).
 *
 * The repo copy is untouched: edit papers-config.js as before.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const DETAIL_FIELDS = ['questions', 'markSchemes'];
const DATA_DIR = 'papers-data';
// Everything from here to the end of the file is helpers, kept verbatim.
const HELPERS_MARKER = '\n// Flatten every direct paper';

function splitPapersConfig(outDir) {
  const file = path.join(outDir, 'papers-config.js');
  const src = fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
  const helpersAt = src.indexOf(HELPERS_MARKER);
  if (helpersAt < 0) throw new Error(`split-papers-config: "${HELPERS_MARKER.trim()}" not found in papers-config.js`);

  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(src, ctx, { filename: 'papers-config.js' });
  const { SUBJECTS, paperParts } = ctx.window;

  fs.mkdirSync(path.join(outDir, DATA_DIR), { recursive: true });
  let split = 0;
  for (const subj of SUBJECTS) {
    for (const board of subj.boards) {
      for (const paper of board.papers || []) {
        if (!DETAIL_FIELDS.some(f => paper[f])) continue;
        if (!/^[A-Za-z0-9_-]+$/.test(paper.id)) throw new Error(`split-papers-config: paper id "${paper.id}" is not file-name safe`);
        const partCount = paperParts(paper).length;
        const data = {};
        for (const f of DETAIL_FIELDS) {
          if (paper[f]) data[f] = paper[f];
          delete paper[f];
        }
        const rel = `${DATA_DIR}/${paper.id}.json`;
        fs.writeFileSync(path.join(outDir, rel), JSON.stringify(data));
        paper.details = rel;
        paper.partCount = partCount;
        split++;
      }
    }
  }

  const out = '// Generated by scripts/split-papers-config.js from the repo\'s papers-config.js.\n' +
    `window.SUBJECTS = ${JSON.stringify(SUBJECTS)};\n` + src.slice(helpersAt);
  fs.writeFileSync(file, out);
  console.log(`split-papers-config: ${split} papers moved to ${DATA_DIR}/, papers-config.js ${(src.length / 1e6).toFixed(1)} MB -> ${(out.length / 1e3).toFixed(0)} KB`);
}

module.exports = { splitPapersConfig };

if (require.main === module) splitPapersConfig(process.argv[2] || path.resolve(__dirname, '..', 'dist'));
